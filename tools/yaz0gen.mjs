// Generates source/nds/yaz0_test_data.h: a Yaz0 blob plus the FNV-1a hash of
// the original bytes, for the on-device decompressor self-test.
import { writeFileSync } from "node:fs";

const WINDOW = 0x1000;
const MAX_LEN = 0x12 + 0xFF; // long-copy ceiling

function makeData() {
  const parts = [];
  let seed = 0x12345678;

  function randBytes(n) {
    const b = Buffer.alloc(n);
    for (let i = 0; i < n; i++) {
      seed = (seed * 1664525 + 1013904223) >>> 0;
      b[i] = seed >>> 24;
    }
    return b;
  }

  const base = randBytes(2048);
  parts.push(base);
  parts.push(Buffer.from("Ocarina of Time DSi port - Yaz0 stream test. ".repeat(48).slice(0, 2048)));
  parts.push(Buffer.alloc(512, 0x5a));
  const patterned = randBytes(2048);
  for (let i = 0; i < patterned.length; i += 32) patterned[i] = 0xa5;
  parts.push(patterned);
  parts.push(Buffer.from(patterned)); // matches at distance 2048
  parts.push(randBytes(1536));
  return Buffer.concat(parts);
}

function findMatch(src, pos) {
  const limit = Math.min(MAX_LEN, src.length - pos);
  let bestLen = 0;
  let bestStart = 0;
  const start = Math.max(0, pos - WINDOW);
  for (let cand = pos - 1; cand >= start; cand--) {
    let len = 0;
    while (len < limit && src[cand + len] === src[pos + len]) len++;
    if (len > bestLen) {
      bestLen = len;
      bestStart = cand;
      if (len === limit) break;
    }
  }
  return bestLen >= 3 ? { len: bestLen, start: bestStart } : null;
}

function compress(src) {
  const out = [];
  out.push(0x59, 0x61, 0x7a, 0x30);
  const n = src.length;
  out.push((n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255);
  out.push(0, 0, 0, 0, 0, 0, 0, 0); // compInfoOffset / uncompDataOffset (unused)
  let pos = 0;
  while (pos < n) {
    const codePos = out.length;
    out.push(0);
    let code = 0;
    for (let i = 0; i < 8 && pos < n; i++) {
      const m = findMatch(src, pos);
      if (!m) {
        code |= 0x80 >> i;
        out.push(src[pos++]);
        continue;
      }
      const dist = pos - m.start - 1;
      if (m.len >= 0x12) {
        out.push((dist >>> 8) & 0x0f, dist & 0xff, m.len - 0x12);
      } else {
        out.push(((m.len - 2) << 4) | ((dist >>> 8) & 0x0f), dist & 0xff);
      }
      pos += m.len;
    }
    out[codePos] = code;
  }
  return Buffer.from(out);
}

function fnv1a(buf) {
  let h = 0x811c9dc5;
  for (const b of buf) {
    h ^= b;
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

const data = makeData();
const packed = compress(data);
const hash = fnv1a(data);

const lines = [];
lines.push("/* Generated by tools/yaz0gen.mjs - do not edit. */");
lines.push("#ifndef OCARINA_NDS_YAZ0_TEST_DATA_H");
lines.push("#define OCARINA_NDS_YAZ0_TEST_DATA_H");
lines.push("");
lines.push(`#define YAZ0_TEST_SIZE ${data.length}u`);
lines.push(`#define YAZ0_TEST_HASH 0x${hash.toString(16).padStart(8, "0")}u`);
lines.push(`#define YAZ0_TEST_PACKED_SIZE ${packed.length}u`);
lines.push("");
lines.push("static const unsigned char yaz0TestPacked[] = {");
for (let i = 0; i < packed.length; i += 12) {
  lines.push("    " + Array.from(packed.subarray(i, i + 12)).map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
}
lines.push("};");
lines.push("");
lines.push("#endif");
lines.push("");

const target = process.argv[2];
writeFileSync(target, lines.join("\n"));
console.log(`data ${data.length} B -> packed ${packed.length} B (${((packed.length / data.length) * 100).toFixed(1)}%), hash 0x${hash.toString(16)}`);
